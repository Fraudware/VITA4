#!/usr/bin/env python3
"""Generate src/font_data.h: anti-aliased ASCII glyph atlases for the PS4 UI.

Renders Inter (SIL Open Font License 1.1) at a few fixed pixel sizes into
8-bit alpha bitmaps, so the app needs no font library at runtime.

    python3 tools/make_font.py [path/to/fonts/dir]
"""
import os
import sys

from PIL import Image, ImageDraw, ImageFont

FONT_DIR = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/opentype/inter"
OUT = os.path.join(os.path.dirname(__file__), "..", "src", "font_data.h")

# (C identifier, font file, pixel size)
FACES = [
    ("font_body", "Inter-Regular.otf", 30),
    ("font_label", "Inter-SemiBold.otf", 30),
    ("font_small", "Inter-Regular.otf", 24),
    ("font_title", "Inter-Bold.otf", 64),
    ("font_heading", "Inter-SemiBold.otf", 42),
]
FIRST, LAST = 32, 126


def build(name, file, size):
    font = ImageFont.truetype(os.path.join(FONT_DIR, file), size)
    ascent, descent = font.getmetrics()
    height = ascent + descent
    glyphs = []
    pixels = bytearray()
    for code in range(FIRST, LAST + 1):
        ch = chr(code)
        advance = int(round(font.getlength(ch)))
        left, top, right, bottom = font.getbbox(ch)
        w = max(0, right - left)
        h = max(0, bottom - top)
        offset = len(pixels)
        if w and h:
            im = Image.new("L", (w, h), 0)
            ImageDraw.Draw(im).text((-left, -top), ch, font=font, fill=255)
            pixels += im.tobytes()
        glyphs.append((offset, w, h, left, top, advance))
    return name, ascent, height, glyphs, pixels


def emit(faces):
    out = []
    out.append("// Generated by tools/make_font.py - do not edit.")
    out.append("// Glyphs rendered from Inter (SIL Open Font License 1.1, see assets/Inter-LICENSE.txt).")
    out.append("#pragma once")
    out.append("#include <stdint.h>")
    out.append('#include "font.h"')
    out.append("")
    for name, ascent, height, glyphs, pixels in faces:
        out.append(f"static const uint8_t {name}_pixels[{max(1, len(pixels))}] = {{")
        row = []
        for i, b in enumerate(pixels):
            row.append(str(b))
            if len(row) == 32:
                out.append("  " + ",".join(row) + ",")
                row = []
        if row:
            out.append("  " + ",".join(row) + ",")
        if not pixels:
            out.append("  0")
        out.append("};")
        out.append(f"static const Glyph {name}_glyphs[{len(glyphs)}] = {{")
        for (offset, w, h, left, top, advance) in glyphs:
            out.append(f"  {{{offset},{w},{h},{left},{top},{advance}}},")
        out.append("};")
        out.append(
            f"static const Font {name} = {{ {name}_glyphs, {name}_pixels, {ascent}, {height}, {FIRST}, {LAST} }};"
        )
        out.append("")
    return "\n".join(out) + "\n"


def main():
    faces = [build(*f) for f in FACES]
    with open(OUT, "w") as fh:
        fh.write(emit(faces))
    total = sum(len(f[4]) for f in faces)
    print(f"wrote {OUT}: {len(faces)} faces, {total} glyph bytes")


if __name__ == "__main__":
    main()
